#!/usr/bin/env python3
"""Generate FRACTURE embedded assets: bitmap font atlas, application icon, logo, banner."""
import os, struct, math, random
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "core")
ASSETS = os.path.join(ROOT, "assets")
os.makedirs(SRC, exist_ok=True)
os.makedirs(ASSETS, exist_ok=True)

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
]

CELL_W, CELL_H = 16, 32
COLS, ROWS = 16, 6
W, H = CELL_W * COLS, CELL_H * ROWS
font = ImageFont.truetype(FONT_CANDIDATES[0], 26)

atlas = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(atlas)
for code in range(32, 127):
    ch = chr(code)
    idx = code - 32
    cx = (idx % COLS) * CELL_W
    cy = (idx // COLS) * CELL_H
    if ch == ' ':
        # white block used for untextured UI quads
        d.rectangle([cx + 5, cy + 12, cx + 11, cy + 18], fill=255)
        continue
    # centre horizontally, baseline near the bottom with 3px descent room
    bbox = d.textbbox((0, 0), ch, font=font)
    gw = bbox[2] - bbox[0]
    gh = bbox[3] - bbox[1]
    x = cx + (CELL_W - gw) // 2 - bbox[0]
    y = cy + (CELL_H - gh) // 2 - bbox[1]
    d.text((x, y), ch, font=font, fill=255)

data = atlas.tobytes()
with open(os.path.join(SRC, "fontatlas.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py — DejaVu Sans Mono Bold bitmap atlas\n")
    f.write("#pragma once\n")
    f.write(f"#define FONT_ATLAS_W {W}\n#define FONT_ATLAS_H {H}\n")
    f.write(f"#define FONT_CELL_W {CELL_W}\n#define FONT_CELL_H {CELL_H}\n")
    f.write(f"#define FONT_COLS {COLS}\n")
    f.write(f"static const unsigned char FONT_ALPHA[{W*H}] = {{\n")
    for i in range(0, len(data), 32):
        f.write(",".join(str(b) for b in data[i:i+32]) + ",\n")
    f.write("};\n")
print("font atlas", W, H, len(data))

# ---------------------------------------------------------------- icon
def make_icon(size):
    img = Image.new("RGBA", (size, size), (10, 12, 15, 255))
    d = ImageDraw.Draw(img)
    rng = random.Random(7)
    # background voxel grid, subtly lit
    n = 10
    cell = size / n
    for gy in range(n):
        for gx in range(n):
            v = 18 + int(26 * (1 - gy / n)) + rng.randint(-5, 5)
            d.rectangle([gx * cell, gy * cell, (gx + 1) * cell, (gy + 1) * cell], fill=(v, v + 2, v + 5, 255))
    # fracture cracks
    for k in range(7):
        x, y = rng.uniform(0.1, 0.9) * size, rng.uniform(0.1, 0.9) * size
        pts = [(x, y)]
        for s in range(rng.randint(3, 6)):
            x += rng.uniform(-0.22, 0.22) * size
            y += rng.uniform(-0.22, 0.22) * size
            pts.append((x, y))
        d.line(pts, fill=(255, 122, 26, 230), width=max(2, size // 42))
        d.line([(p[0] + 1, p[1] + 1) for p in pts], fill=(255, 196, 90, 150), width=max(1, size // 90))
    # bold F glyph
    try:
        f1 = ImageFont.truetype(FONT_CANDIDATES[1], int(size * 0.72))
    except Exception:
        f1 = ImageFont.load_default()
    bbox = d.textbbox((0, 0), "F", font=f1)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    tx, ty = (size - tw) // 2 - bbox[0], (size - th) // 2 - bbox[1] - int(size * 0.03)
    for ox, oy in [(-2, 2), (2, 2), (0, 4)]:
        d.text((tx + ox, ty + oy), "F", font=f1, fill=(0, 0, 0, 200))
    d.text((tx, ty), "F", font=f1, fill=(240, 238, 232, 255))
    # hazard stripe band
    band_y = int(size * 0.82)
    bh = max(3, int(size * 0.06))
    for i in range(-size, size * 2, max(4, size // 12)):
        d.polygon([(i, band_y), (i + size // 24, band_y), (i + size // 24 - bh, band_y + bh), (i - bh, band_y + bh)],
                  fill=(255, 138, 30, 255))
    return img

sizes = [16, 32, 48, 64, 128, 256]
imgs = [make_icon(s) for s in sizes]
imgs[-1].save(os.path.join(ASSETS, "icon.ico"), format="ICO", sizes=[(s, s) for s in sizes])
imgs[-1].save(os.path.join(ASSETS, "icon.png"))
print("icon written")

# ---------------------------------------------------------------- logo / banner
def make_banner(w=1280, h=400):
    img = Image.new("RGB", (w, h), (13, 15, 19))
    d = ImageDraw.Draw(img)
    rng = random.Random(3)
    for y in range(h):
        t = y / h
        d.line([(0, y), (w, y)], fill=(int(14 + 18 * t), int(16 + 20 * t), int(21 + 24 * t)))
    # voxel rubble silhouette along bottom
    for i in range(70):
        bx = rng.randint(-20, w)
        bw = rng.randint(20, 90)
        bh = rng.randint(8, 70)
        shade = rng.randint(24, 48)
        d.rectangle([bx, h - bh, bx + bw, h], fill=(shade, shade + 2, shade + 5))
        d.rectangle([bx, h - bh, bx + bw, h - bh + 3], fill=(shade + 30, shade + 26, shade + 20))
    try:
        big = ImageFont.truetype(FONT_CANDIDATES[1], 118)
        small = ImageFont.truetype(FONT_CANDIDATES[0], 34)
        tiny = ImageFont.truetype(FONT_CANDIDATES[0], 22)
    except Exception:
        big = small = tiny = ImageFont.load_default()
    title = "FRACTURE"
    d.text((62, 70), title, font=big, fill=(240, 236, 228))
    d.text((66, 76), title, font=big, fill=(255, 126, 30))
    d.text((66, 70), title, font=big, fill=(245, 240, 232))
    d.text((68, 196), "TOTAL DESTRUCTION", font=small, fill=(255, 138, 30))
    d.text((68, 240), "VOXEL DEMOLITION SANDBOX  ·  WINDOWS PC", font=tiny, fill=(150, 156, 164))
    d.line([(64, 300), (560, 300)], fill=(255, 138, 30), width=2)
    for x in range(0, w, 8):
        if (x // 8) % 2 == 0:
            d.rectangle([x, h - 8, x + 8, h], fill=(255, 138, 30, 255))
    img.save(os.path.join(ASSETS, "banner.png"))
    return img

make_banner()
print("banner written")

# ---------------------------------------------------------------- ico for windows resource (single ico with all sizes)
print("done")
