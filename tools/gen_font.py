#!/usr/bin/env python3
"""Generate the embedded FRACTURE font atlas (DejaVu Sans, regular + bold).
Outputs src/ft/font_data.h (decls + metrics) and src/ft/font_data.cpp (pixels)."""
from PIL import Image, ImageDraw, ImageFont
import os, sys

FONT_PX = 40
CELL = 48
COLS = 16
GLYPHS = list(range(32, 127))  # 95 glyphs
ROWS_PER = (len(GLYPHS) + COLS - 1) // COLS  # 6
ROWS = ROWS_PER * 2            # regular + bold
W, H = COLS * CELL, ROWS * CELL

REGULAR = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "src", "ft")

def main():
    img = Image.new("L", (W, H), 0)
    metrics = [[None] * len(GLYPHS) for _ in range(2)]
    for style, path in enumerate((REGULAR, BOLD)):
        if not os.path.exists(path):
            print("missing font:", path); sys.exit(1)
        font = ImageFont.truetype(path, FONT_PX)
        ascent, descent = font.getmetrics()
        draw = ImageDraw.Draw(img)
        for i, ch in enumerate(GLYPHS):
            col, row = i % COLS, i // COLS + style * ROWS_PER
            ox, oy = col * CELL, row * CELL
            chstr = chr(ch)
            bbox = font.getbbox(chstr)  # relative to origin, anchor 'la'
            x0, y0, x1, y1 = bbox
            adv = font.getlength(chstr)
            # render glyph into its cell at origin
            cell = Image.new("L", (CELL, CELL), 0)
            cdraw = ImageDraw.Draw(cell)
            cdraw.text((0, 0), chstr, font=font, fill=255, anchor="la")
            img.paste(cell, (ox, oy))
            gw = max(0, x1 - x0)
            gh = max(0, y1 - y0)
            metrics[style][i] = (adv, x0, y0, gw, gh)
    # emit
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "font_data.h"), "w") as f:
        f.write("// GENERATED by tools/gen_font.py — DejaVu Sans (see THIRD_PARTY_NOTICES.txt)\n#pragma once\n")
        f.write(f"#define FT_FONT_PX {FONT_PX}\n#define FT_FONT_CELL {CELL}\n")
        f.write(f"#define FT_FONT_COLS {COLS}\n#define FT_FONT_ROWS {ROWS}\n")
        f.write(f"#define FT_FONT_W {W}\n#define FT_FONT_H {H}\n")
        f.write("struct FTGlyph { short adv, x, y, w, h; }; // px*64 @ FT_FONT_PX (x,y signed: glyph overhang)\n")
        f.write("extern const unsigned char FT_FONT_DATA[FT_FONT_W * FT_FONT_H];\n")
        f.write("extern const FTGlyph FT_FONT_GLYPHS[2][95];\n")
        f.write("extern const unsigned short FT_FONT_ASCENT; // px @ FT_FONT_PX\n")
    pix = img.tobytes()
    with open(os.path.join(OUT_DIR, "font_data.cpp"), "w") as f:
        f.write('// GENERATED by tools/gen_font.py\n#include "font_data.h"\n')
        f.write(f"const unsigned short FT_FONT_ASCENT = {metrics[0][0] and ImageFont.truetype(REGULAR, FONT_PX).getmetrics()[0]};\n")
        f.write("const unsigned char FT_FONT_DATA[FT_FONT_W * FT_FONT_H] = {\n")
        for i in range(0, len(pix), 32):
            chunk = pix[i:i+32]
            f.write(",".join(str(b) for b in chunk) + ",\n")
        f.write("};\n")
        f.write("const FTGlyph FT_FONT_GLYPHS[2][95] = {\n")
        for style in range(2):
            f.write("  {\n")
            for i, (adv, x0, y0, gw, gh) in enumerate(metrics[style]):
                f.write(f"    {{{int(round(adv*64))},{int(x0)*64},{int(y0)*64},{int(gw)*64},{int(gh)*64}}},")
                if i % 8 == 7: f.write("\n")
            f.write("\n  },\n")
        f.write("};\n")
    print("wrote font_data.h/.cpp", W, "x", H)

if __name__ == "__main__":
    main()
