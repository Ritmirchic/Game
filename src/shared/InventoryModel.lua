--!strict
--[[
	InventoryModel — grid inventory, pure logic (no Roblox services).
	Shared by the server (authority) and the client (prediction/preview).

	Container layout
	  {
	    id       = "Backpack",
	    cols     = 6, rows = 6,
	    items    = { [uid] = { uid, itemId, x, y, count, dur } }
	  }
	A `uid` is generated by the server; the client never invents one.
]]

local Items = require(script.Parent.ItemDefinitions)
local Config = require(script.Parent.Config)

local Inventory = {}
Inventory.__index = Inventory

local nextUidCounter = 0

function Inventory.newUid()
	nextUidCounter += 1
	return string.format("i%06d%s", nextUidCounter, tostring(math.random(100000, 999999)))
end

function Inventory.newContainer(id, cols, rows)
	return { id = id, cols = cols, rows = rows, items = {} }
end

function Inventory.footprint(itemId)
	local def = Items[itemId]
	if not def then return 1, 1 end
	return def.w, def.h
end

function Inventory.newState()
	return {
		containers = {
			Backpack = Inventory.newContainer("Backpack", Config.Grid.BackpackCols, Config.Grid.BackpackRows),
			Pockets = Inventory.newContainer("Pockets", Config.Grid.PocketCols, Config.Grid.PocketRows),
			Ammo = Inventory.newContainer("Ammo", Config.Grid.AmmoCols, Config.Grid.AmmoRows),
		},
		equipment = {},
		weight = 0,
	}
end

-- occupancy grid helpers ----------------------------------------------------
local function buildGrid(container)
	local grid = {}
	for y = 1, container.rows do
		grid[y] = {}
		for x = 1, container.cols do
			grid[y][x] = nil
		end
	end
	for uid, entry in pairs(container.items) do
		local w, h = Inventory.footprint(entry.itemId)
		for dy = 0, h - 1 do
			for dx = 0, w - 1 do
				local gx, gy = entry.x + dx, entry.y + dy
				if grid[gy] and grid[gy][gx] ~= nil or (grid[gy] and grid[gy][gx] == nil and false) then
					-- occupied marker handled below
				end
				if grid[gy] then
					grid[gy][gx] = uid
				end
			end
		end
	end
	return grid
end

function Inventory.canPlace(container, itemId, x, y, ignoreUid)
	local w, h = Inventory.footprint(itemId)
	if x < 1 or y < 1 or x + w - 1 > container.cols or y + h - 1 > container.rows then
		return false, "out of bounds"
	end
	for _, entry in pairs(container.items) do
		if entry.uid ~= ignoreUid then
			local ew, eh = Inventory.footprint(entry.itemId)
			local overlapX = x < entry.x + ew and x + w > entry.x
			local overlapY = y < entry.y + eh and y + h > entry.y
			if overlapX and overlapY then
				return false, "occupied"
			end
		end
	end
	return true
end

function Inventory.findFreeSpot(container, itemId)
	if not container then return nil end
	local w, h = Inventory.footprint(itemId)
	for y = 1, container.rows - h + 1 do
		for x = 1, container.cols - w + 1 do
			if Inventory.canPlace(container, itemId, x, y) then
				return x, y
			end
		end
	end
	return nil
end

function Inventory.countItem(state, itemId, includeEquipment)
	local total = 0
	for _, container in pairs(state.containers) do
		for _, entry in pairs(container.items) do
			if entry.itemId == itemId then
				total += entry.count or 1
			end
		end
	end
	if includeEquipment then
		for _, entry in pairs(state.equipment) do
			if entry and entry.itemId == itemId then
				total += entry.count or 1
			end
		end
	end
	return total
end

function Inventory.totalWeight(state)
	local weight = 0
	for _, container in pairs(state.containers) do
		for _, entry in pairs(container.items) do
			local def = Items[entry.itemId]
			if def then
				weight += def.weight * (entry.count or 1)
			end
		end
	end
	for _, entry in pairs(state.equipment) do
		if entry then
			local def = Items[entry.itemId]
			if def then
				weight += def.weight * (entry.count or 1)
			end
		end
	end
	return weight
end

function Inventory.capacity(state)
	local base = Config.Grid.MaxWeightBase
	local pack = state.equipment.Backpack
	if pack then
		local def = Items[pack.itemId]
		if def and def.id == "backpack" then
			base += 14
		end
	end
	return base
end

-- Returns uid or nil. `def` may be nil if itemId is unknown (rejected).
function Inventory.addItem(state, itemId, count, prefer)
	local def = Items[itemId]
	if not def then return nil, "unknown item" end
	count = math.max(1, math.floor(count or 1))

	local order = { "Backpack", "Pockets", "Ammo" }
	if prefer then
		table.insert(order, 1, prefer)
	end
	for _, containerId in ipairs(order) do
		local container = state.containers[containerId]
		if container then
			if def.stack > 1 then
				for _, entry in pairs(container.items) do
					if entry.itemId == itemId and (entry.count or 1) < def.stack then
						local space = def.stack - (entry.count or 1)
						local moved = math.min(space, count)
						entry.count = (entry.count or 1) + moved
						count -= moved
						if count <= 0 then
							return entry.uid, nil
						end
					end
				end
			end
			while count > 0 do
				local x, y = Inventory.findFreeSpot(container, itemId)
				if not x then break end
				local take = math.min(def.stack, count)
				local uid = Inventory.newUid()
				local entry = {
					uid = uid, itemId = itemId, x = x, y = y, count = take,
					dur = def.dur,
				}
				container.items[uid] = entry
				count -= take
				if count <= 0 then
					return uid, nil
				end
			end
		end
	end
	return nil, count > 0 and "no space" or nil
end

function Inventory.removeByUid(state, uid, count)
	for _, container in pairs(state.containers) do
		local entry = container.items[uid]
		if entry then
			count = count or entry.count or 1
			entry.count = (entry.count or 1) - count
			if entry.count <= 0 then
				container.items[uid] = nil
				return true, entry
			end
			return true, entry
		end
	end
	for slot, entry in pairs(state.equipment) do
		if entry and entry.uid == uid then
			state.equipment[slot] = nil
			return true, entry
		end
	end
	return false, nil
end

function Inventory.findUid(state, uid)
	for _, container in pairs(state.containers) do
		if container.items[uid] then return container.items[uid], container end
	end
	for slot, entry in pairs(state.equipment) do
		if entry and entry.uid == uid then return entry, nil, slot end
	end
	return nil
end

function Inventory.consumeItem(state, itemId, count)
	local remaining = count
	for _, container in pairs(state.containers) do
		for uid, entry in pairs(container.items) do
			if entry.itemId == itemId and remaining > 0 then
				local take = math.min(remaining, entry.count or 1)
				entry.count = (entry.count or 1) - take
				remaining -= take
				if entry.count <= 0 then
					container.items[uid] = nil
				end
			end
		end
	end
	return remaining == 0
end

function Inventory.serialize(state)
	local out = { containers = {}, equipment = {}, weight = Inventory.totalWeight(state),
		capacity = Inventory.capacity(state) }
	for id, container in pairs(state.containers) do
		local items = {}
		for uid, entry in pairs(container.items) do
			items[uid] = {
				uid = entry.uid, itemId = entry.itemId, x = entry.x, y = entry.y,
				count = entry.count or 1, dur = entry.dur,
			}
		end
		out.containers[id] = { id = id, cols = container.cols, rows = container.rows, items = items }
	end
	for slot, entry in pairs(state.equipment) do
		if entry then
			out.equipment[slot] = {
				uid = entry.uid, itemId = entry.itemId, count = entry.count or 1, dur = entry.dur,
			}
		end
	end
	return out
end

function Inventory.deserialize(data)
	local state = Inventory.newState()
	if type(data) ~= "table" then return state end
	for id, container in pairs(data.containers or {}) do
		local target = state.containers[id]
		if not target then
			target = Inventory.newContainer(id, container.cols or 4, container.rows or 4)
			state.containers[id] = target
		end
		for uid, entry in pairs(container.items or {}) do
			if type(entry) == "table" and Items[entry.itemId] then
				target.items[uid] = {
					uid = uid, itemId = entry.itemId, x = entry.x, y = entry.y,
					count = entry.count or 1, dur = entry.dur,
				}
			end
		end
	end
	for slot, entry in pairs(data.equipment or {}) do
		if type(entry) == "table" and Items[entry.itemId] then
			state.equipment[slot] = {
				uid = entry.uid or Inventory.newUid(), itemId = entry.itemId,
				count = entry.count or 1, dur = entry.dur,
			}
		end
	end
	return state
end

function Inventory.equipFromUid(state, uid)
	local entry, container = Inventory.findUid(state, uid)
	if not entry then return false, "missing item" end
	local def = Items[entry.itemId]
	if not def or not def.equip then return false, "cannot equip" end
	local slot = def.equip
	local previous = state.equipment[slot]
	if container then
		container.items[uid] = nil
	end
	state.equipment[slot] = entry
	if previous then
		-- return previously equipped item to a free slot
		local x, y = Inventory.findFreeSpot(state.containers.Backpack, previous.itemId)
		local target = state.containers.Backpack
		if not x then
			target = state.containers.Pockets
			x, y = Inventory.findFreeSpot(target, previous.itemId)
		end
		if x then
			previous.x, previous.y = x, y
			target.items[previous.uid] = previous
		end
	end
	return true, slot
end

function Inventory.unequip(state, slot)
	local entry = state.equipment[slot]
	if not entry then return false end
	state.equipment[slot] = nil
	local x, y = Inventory.findFreeSpot(state.containers.Backpack, entry.itemId)
	local target = state.containers.Backpack
	if not x then
		target = state.containers.Pockets
		x, y = Inventory.findFreeSpot(target, entry.itemId)
	end
	if not x then
		state.equipment[slot] = entry
		return false
	end
	entry.x, entry.y = x, y
	target.items[entry.uid] = entry
	return true
end

function Inventory.getEquipped(state, slot)
	return state.equipment[slot]
end

function Inventory.damageEquipped(state, slot, amount)
	local entry = state.equipment[slot]
	if not entry then return end
	local def = Items[entry.itemId]
	if not def or not def.dur then return end
	entry.dur = (entry.dur or def.dur) - amount
	if entry.dur <= 0 then
		state.equipment[slot] = nil
	end
end

return Inventory
