/* ============================================================
   СРЕЗ / SLICE — генератор четырёхмерного мира
   Решётка 32⁴, хранится как 4 среза по W, каждый 32³.
   Значения клетки:
     0 — пусто
     1 — порода (есть во всех срезах)
     2 — призрачная материя: в своём срезе это стена, из соседних — цветное свечение
     3 — «эхо»: неосязаемый след прохода, существующего в другом измерении
   ============================================================ */
(function (root) {
  'use strict';
  const N = 32;
  const IH0 = 1, IH1 = 3, CEIL = 4;   // пол 0..1, объём 1..4, потолок 4
  const idx = (x, y, z) => (y * N + z) * N + x;

  function makeWorld(seedIn) {
    let seed = (seedIn >>> 0) || 1;
    const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
    const ri = (a, b) => a + Math.floor(rnd() * (b - a + 1));

    const grid = [];
    for (let w = 0; w < 4; w++) { const g = new Uint8Array(N * N * N); g.fill(1); grid.push(g); }

    const inb = (x, y, z) => x >= 0 && y >= 0 && z >= 0 && x < N && y < N && z < N;
    const SET = (w, x, y, z, v) => { if (inb(x, y, z)) grid[w][idx(x, y, z)] = v; };
    const GET = (w, x, y, z) => inb(x, y, z) ? grid[w][idx(x, y, z)] : 1;
    const FILL = (w, x0, y0, z0, x1, y1, z1, v) => {
      for (let y = y0; y <= y1; y++) for (let z = z0; z <= z1; z++) for (let x = x0; x <= x1; x++) SET(w, x, y, z, v);
    };
    // вырезать пустоту во всех четырёх срезах
    const CARVE = (x0, y0, z0, x1, y1, z1) => { for (let w = 0; w < 4; w++) FILL(w, x0, y0, z0, x1, y1, z1, 0); };
    // «призрак» только в одном срезе (не трогая пустоту других срезов)
    const GHOST = (w, x0, y0, z0, x1, y1, z1) => {
      for (let y = y0; y <= y1; y++) for (let z = z0; z <= z1; z++) for (let x = x0; x <= x1; x++)
        if (GET(w, x, y, z) === 0) SET(w, x, y, z, 2);
    };

    /* ---------------------------------------------------- 1. общие коридоры
       Одинаковы во всех четырёх срезах — база, по которой всегда можно идти. */
    const SPINE = [
      [13, 2, 18, 7],    // стартовый зал
      [15, 8, 16, 14],   // северный коридор
      [9, 15, 22, 20],   // центральный зал
      [15, 21, 16, 24],  // южный коридор
      [12, 25, 19, 29],  // южный зал
      [3, 17, 8, 18],    // западный коридор
      [23, 17, 28, 18],  // восточный коридор
      [3, 6, 4, 16],     // западная вертикаль
      [27, 6, 28, 16],   // восточная вертикаль
      [3, 5, 14, 6],     // северо-западный коридор
      [19, 5, 28, 6],    // северо-восточный коридор
      [3, 19, 4, 26],    // юго-западная вертикаль
      [27, 19, 28, 26],  // юго-восточная вертикаль
      [3, 27, 11, 28],   // южная перемычка (запад)
      [20, 27, 28, 28],  // южная перемычка (восток)
    ];
    for (const r of SPINE) CARVE(r[0], IH0, r[1], r[2], IH1, r[3]);

    /* ---------------------------------------------------- 1b. призрачная отделка коридоров
       Всё это существует лишь в одном срезе из четырёх. Потолочные балки
       (y=3) не мешают идти, но из соседних измерений выглядят как цветные рёбра.
       Подпорки у стен (y=1..2) стоят на краю коридора — пройти можно рядом. */
    const OPEN = new Uint8Array(N * N);
    for (let z = 0; z < N; z++) for (let x = 0; x < N; x++) {
      let all = 1;
      for (let w = 0; w < 4; w++) if (grid[w][idx(x, 1, z)] !== 0 || grid[w][idx(x, 2, z)] !== 0) { all = 0; break; }
      OPEN[z * N + x] = all;
    }
    const openAt = (x, z) => (x > 0 && z > 0 && x < N - 1 && z < N - 1) ? OPEN[z * N + x] : 0;
    const portageAt = (x, z) => grid[0][idx(x, 1, z)] === 1 && grid[1][idx(x, 1, z)] === 1 &&
                               grid[2][idx(x, 1, z)] === 1 && grid[3][idx(x, 1, z)] === 1;
    for (let z = 1; z < N - 1; z++) for (let x = 1; x < N - 1; x++) {
      if (!openAt(x, z)) continue;
      // локальная «ширина» свободного пространства — подпорки ставим только в залах
      let wx = 1; for (let i = 1; openAt(x + i, z); i++) wx++; for (let i = 1; openAt(x - i, z); i++) wx++;
      let wz = 1; for (let i = 1; openAt(x, z + i); i++) wz++; for (let i = 1; openAt(x, z - i); i++) wz++;
      // угол зала: стена сбоку и стена сзади — подпорка не перекроет проход
      const nearWallX = portageAt(x + 1, z) || portageAt(x - 1, z);
      const nearWallZ = portageAt(x, z + 1) || portageAt(x, z - 1);
      const corner = nearWallX && nearWallZ && wx >= 3 && wz >= 3;
      for (let w = 0; w < 4; w++) {
        const hh = ((x * 73856093) ^ (z * 19349663) ^ (w * 83492791)) >>> 0;
        // потолочные балки — своя решётка у каждого измерения
        if ((x * 2 + z * 3 + w * 5) % 6 === 0) SET(w, x, 3, z, 2);
        else if ((x + z * 2 + w * 7) % 11 === 0) SET(w, x, 3, z, 2);
        // подпорки у стен
        if (corner && hh % 9 === 0) { SET(w, x, 1, z, 2); SET(w, x, 2, z, 2); }
      }
    }

    /* ---------------------------------------------------- 2. тайные камеры
       Объём камеры существует только в своём срезе. В остальных — порода.
       Дверь камеры во всех «чужих» срезах помечена призраком: издалека видно,
       что здесь есть проход в другое измерение. */
    const CHAMBERS = [
      { w: 0, room: [6, 9, 11, 13], door: [8, 7, 9, 8] },     // северо-запад
      { w: 1, room: [19, 9, 24, 13], door: [21, 7, 22, 8] },  // северо-восток
      { w: 2, room: [6, 21, 10, 25], door: [7, 19, 8, 20] },  // юго-запад
      { w: 3, room: [20, 22, 25, 26], door: [24, 19, 25, 21] },// юго-восток
    ];
    for (const c of CHAMBERS) {
      const r = c.room, d = c.door;
      FILL(c.w, r[0], IH0, r[1], r[2], IH1, r[3], 0);
      FILL(c.w, d[0], IH0, d[1], d[2], IH1, d[3], 0);
      for (let ow = 0; ow < 4; ow++) {
        if (ow === c.w) continue;
        FILL(ow, r[0], IH0, r[1], r[2], IH1, r[3], 1);   // камеры нет — сплошная порода
        // дверь-эхо: неосязаемый след прохода, существующего в другом измерении.
        // Породу убираем, оставляем только свечение — «сквозь стену видно, но пройти нельзя».
        for (let y = IH0; y <= IH1; y++) for (let z = d[1]; z <= d[3]; z++) for (let x = d[0]; x <= d[2]; x++) {
          SET(ow, x, y, z, 3);
        }
      }
    }

    /* ---------------------------------------------------- 3. призрачная архитектура
       Разная в каждом срезе. В своём срезе это обычные стены и балки, из соседних
       измерений они просвечивают сквозь пустоту. Всё, что ниже y=3, ставим только
       в широком зале — коридоры должны оставаться проходимыми. */
    // W0 — ЯДРО: симметричная колоннада + потолочные рёбра
    GHOST(0, 13, 3, 2, 18, 3, 2);
    GHOST(0, 13, 3, 7, 18, 3, 7);
    for (let x = 10; x <= 21; x += 3) GHOST(0, x, 3, 15, x, 3, 16);
    for (let z = 16; z <= 19; z += 3) GHOST(0, 15, 3, z, 16, 3, z);
    for (const p of [[11, 16], [11, 19], [13, 17], [18, 17], [20, 16], [20, 19]]) {
      GHOST(0, p[0], IH0, p[1], p[0], IH1, p[1]);
    }

    // W1 — РАЗЛОМ: косые рёбра
    for (let i = 4; i < 28; i += 3) {
      GHOST(1, i, 3, 5, i + 1, 3, 6);
      GHOST(1, i, 3, 17, i + 1, 3, 18);
    }
    for (let k = 0; k < 10; k++) {
      const x = ri(10, 21), z = ri(16, 19);
      GHOST(1, x, IH0, z, x, IH1, z);
      if (k % 2) GHOST(1, x + 1, 3, z, x + 1, 3, z);
    }

    // W2 — ОБРАТНАЯ СТОРОНА: частая гребёнка
    for (let x = 4; x < 30; x += 2) { GHOST(2, x, 3, 5, x, 3, 6); GHOST(2, x, 3, 17, x, 3, 18); }
    for (let z = 8; z < 15; z += 2) GHOST(2, 15, 3, z, 16, 3, z);
    GHOST(2, 9, IH0, 18, 13, IH1, 18);
    GHOST(2, 18, IH0, 17, 22, IH1, 17);
    for (let x = 10; x <= 21; x += 2) GHOST(2, x, 3, 15, x, 3, 20);

    // W3 — ТИШИНА: редкие парящие плиты
    for (let x = 4; x < 30; x += 5) { GHOST(3, x, 3, 5, x, 3, 6); GHOST(3, x, 3, 17, x, 3, 18); }
    for (let z = 8; z < 15; z += 4) GHOST(3, 15, 3, z, 16, 3, z + 1);
    for (let k = 0; k < 14; k++) {
      const x = ri(9, 21), z = ri(15, 20);
      GHOST(3, x, 3, z, Math.min(x + ri(0, 2), 22), 3, Math.min(z + ri(0, 2), 20));
    }
    GHOST(3, 11, IH0, 16, 11, IH1, 16);
    GHOST(3, 19, IH0, 19, 19, IH1, 19);
    GHOST(3, 15, IH0, 9, 16, IH1, 9);

    /* ---------------------------------------------------- 4. свет в камерах
       Камеры получают собственные «окна» — призрачные рёбра по периметру. */
    for (const c of CHAMBERS) {
      const r = c.room;
      for (let x = r[0]; x <= r[2]; x += 2) { GHOST(c.w, x, 3, r[1], x, 3, r[1]); GHOST(c.w, x, 3, r[3], x, 3, r[3]); }
      for (let z = r[1]; z <= r[3]; z += 2) { GHOST(c.w, r[0], 3, z, r[0], 3, z); GHOST(c.w, r[2], 3, z, r[2], 3, z); }
    }

    /* ---------------------------------------------------- 5. точки */
    const FRAGS = CHAMBERS.map((c) => ({
      w: c.w,
      x: (c.room[0] + c.room[2]) / 2 + 0.5,
      z: (c.room[1] + c.room[3]) / 2 + 0.5,
    }));
    const SPAWN = { x: 15.5, z: 5.5, yaw: 0 };
    const CORE = { x: 15.5, z: 2.6 };

    /* ---------------------------------------------------- 5b. лампы
       Тёплые лампы в потолке над коридорами. Горят во всех срезах сразу —
       единственное, что не зависит от W. */
    const lamps = new Uint8Array(N * N * N);
    const addLamp = (x, y, z) => { if (inb(x, y, z)) { SET(0, x, y, z, 0); lamps[idx(x, y, z)] = 1; } };
    for (let z = 3; z <= 12; z += 4) addLamp(15, CEIL, z);
    for (let z = 20; z <= 28; z += 4) addLamp(16, CEIL, z);
    for (let x = 4; x <= 12; x += 4) { addLamp(x, CEIL, 17); addLamp(x, CEIL, 27); }
    for (let x = 20; x <= 28; x += 4) { addLamp(x, CEIL, 17); addLamp(x, CEIL, 27); }
    for (let z = 8; z <= 14; z += 3) addLamp(15, CEIL, z);
    for (let x = 4; x <= 28; x += 6) addLamp(x, CEIL, 5);
    // лампы в тайных камерах — их видно даже из чужого измерения
    for (const c of CHAMBERS) {
      const r = c.room;
      addLamp((r[0] + r[2]) >> 1, CEIL, (r[1] + r[3]) >> 1);
      addLamp(r[0] + 1, CEIL, r[1] + 1); addLamp(r[2] - 1, CEIL, r[3] - 1);
    }

    /* ---------------------------------------------------- 6. occ-маска
       Байт на клетку: младшие 4 бита — порода в срезе w, старшие 4 — призрак.
       Рамка = 0xFF (луч вышел за пределы мира). */
    const P2 = N + 2, S2 = P2 * P2;
    const occ = new Uint8Array(P2 * P2 * P2);
    occ.fill(0xFF);
    for (let y = 0; y < N; y++) for (let z = 0; z < N; z++) for (let x = 0; x < N; x++) {
      const gi = idx(x, y, z);
      let m = 0;
      for (let w = 0; w < 4; w++) {
        const v = grid[w][gi];
        if (v === 1 || v === 2) m |= 1 << w;
        if (v === 2 || v === 3) m |= 1 << (w + 4);
      }
      occ[(y + 1) * S2 + (z + 1) * P2 + (x + 1)] = m;
    }

    return { N, grid, occ, lamps, P: P2, S: S2, FRAGS, SPAWN, CORE, CEIL, IH0, IH1, idx, CHAMBERS, SPINE };
  }

  const api = { makeWorld, N };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.World = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
